`default_nettype none

module apb_led_slave #(
    parameter NUM_SLAVES = 8,
    parameter ADDR_WIDTH = 32,
    parameter DATA_WIDTH = 32
)(
    // APB Interface (Matches ahb2apb_bridge combined buses)
    input  wire                               pclk,
    input  wire                               presetn,
    input  wire [ADDR_WIDTH-1:0]              paddr,
    input  wire [NUM_SLAVES-1:0]              psel,
    input  wire                               penable,
    input  wire                               pwrite,
    input  wire [DATA_WIDTH-1:0]              pwdata,
    input  wire [(DATA_WIDTH/8)-1:0]          pstrb,
    
    // Outputs driven back to the bridge
    output wire [(DATA_WIDTH*NUM_SLAVES)-1:0] prdata_bus,
    output wire [NUM_SLAVES-1:0]              pready_bus,
    output wire [NUM_SLAVES-1:0]              pslverr_bus,
    
    // External Hardware Pins
    output wire [7:0]                         leds
);

    // We will map this module to Slave 0
    wire sel_0 = psel[0];
    
    // Internal 32-bit register for the LEDs
    reg [31:0] led_reg;
    
    // Drive Slave 0's ready/error signals, tie others to 0
    assign pready_bus  = { {(NUM_SLAVES-1){1'b0}}, 1'b1 }; 
    assign pslverr_bus = {NUM_SLAVES{1'b0}};
    
    // Read data multiplexing: drive data to Slave 0 slice, pad the rest with 0s
    reg [31:0] prdata_0;
    assign prdata_bus = { {((NUM_SLAVES-1)*DATA_WIDTH){1'b0}}, prdata_0 };
    
    // Wire the bottom 8 bits to the physical LEDs
    assign leds = led_reg[7:0];

    // APB Write Logic (Slave 0)
    always @(posedge pclk or negedge presetn) begin
        if (!presetn) begin
            led_reg <= 32'd0;
        end else begin
            // Write when selected, enabled, and write signal is high
            if (sel_0 && penable && pwrite) begin
                // Supporting the byte strobes generated by your master FSM
                if (pstrb[0]) led_reg[7:0]   <= pwdata[7:0];
                if (pstrb[1]) led_reg[15:8]  <= pwdata[15:8];
                if (pstrb[2]) led_reg[23:16] <= pwdata[23:16];
                if (pstrb[3]) led_reg[31:24] <= pwdata[31:24];
            end
        end
    end

    // APB Read Logic (Slave 0)
    always @(*) begin
        if (sel_0 && !pwrite) begin
            prdata_0 = led_reg;
        end else begin
            prdata_0 = 32'd0;
        end
    end

endmodule